#include <libft/std_string.h>

int	ft_str_pop(t_string *str)
{
	char	c;

	if (str->len == 0)
		return (-1);
	c = str->str[str->len - 1];
	str->str[str->len - 1] = '\0';
	str->len--;
	return (c);
}
